/**
 * Live Meetings validation schemas.
 *
 * All schemas use `.strict()` so that untrusted form input cannot
 * smuggle privileged fields (`created_by`, `started_at`, `ended_at`,
 * `room_name`, `status`) into server actions. The repository and
 * server-side business logic assign those fields and re-validate
 * business rules (status transitions, future-dating, timestamp
 * consistency) independently of these schemas.
 */

import { z } from "zod";

import {
  MEETING_STATUS,
  type MeetingStatus,
} from "@/lib/types/meeting";

/**
 * Shared primitive rules.
 */

const meetingIdSchema = z
  .string()
  .uuid("Invalid meeting ID.");

const displayNameSchema = z
  .string()
  .trim()
  .min(2, "Jina la kinafsi lazima liwe na herufi mbili au zaidi.")
  .max(100, "Jina la kinafsi halipaswi kuwa na herufi zaidi ya 100.");

const titleSchema = z
  .string()
  .trim()
  .min(2, "Kichwa cha mkutano lazima kiwe na herufi mbili au zaidi.")
  .max(200, "Kichwa cha mkutano halipaswi kuwa na herufi zaidi ya 200.");

const descriptionSchema = z
  .string()
  .trim()
  .max(2000, "Maelezo ya mkutano halipaswi kuwa na herufi zaidi ya 2000.")
  .nullable();

/**
 * `scheduledStartAt` is accepted as an ISO-8601 string. It must
 * parse to a real Date and, when creating a meeting, must lie in the
 * future. The server-side business logic re-checks this rule.
 */
const scheduledStartAtSchema = z
  .string()
  .trim()
  .refine(
    (value) => !Number.isNaN(Date.parse(value)),
    "Tarehe ya kuanza si sahihi.",
  )
  .refine(
    (value) => Date.parse(value) > Date.now(),
    "Mkutano unapaswa kuanza baada ya sasa.",
  );

/**
 * 1. Create a meeting.
 *
 * Privileged fields are intentionally omitted:
 *   - `created_by` is derived from the authenticated session.
 *   - `status` defaults to `scheduled` in the repository.
 *   - `room_name` is generated by the repository to preserve the
 *     unique constraint.
 *   - `started_at` / `ended_at` are managed by status transitions.
 */
export const createMeetingSchema = z
  .object({
    title: titleSchema,
    description: descriptionSchema,
    scheduledStartAt: scheduledStartAtSchema,
  })
  .strict();

export type CreateMeetingInput = z.infer<
  typeof createMeetingSchema
>;

/**
 * 2. Update a meeting.
 *
 * Partial update. All fields optional. Privileged fields remain
 * absent so clients cannot mutate them.
 */
export const updateMeetingSchema = z
  .object({
    title: titleSchema.optional(),
    description: descriptionSchema.optional(),
    scheduledStartAt: scheduledStartAtSchema.optional(),
  })
  .strict()
  .refine(
    (data) =>
      data.title !== undefined ||
      data.description !== undefined ||
      data.scheduledStartAt !== undefined,
    "Hakuna taarifa iliyobadilishwa.",
  );

export type UpdateMeetingInput = z.infer<
  typeof updateMeetingSchema
>;

/**
 * 3. Register a citizen for a meeting.
 *
 * `displayName` is the only citizen-supplied field. `meetingId`
 * identifies the meeting. `user_id` is derived from the session on
 * the server when available.
 */
export const registerMeetingSchema = z
  .object({
    meetingId: meetingIdSchema,
    displayName: displayNameSchema,
  })
  .strict();

export type RegisterMeetingInput = z.infer<
  typeof registerMeetingSchema
>;

/**
 * 4. Unregister a citizen from a meeting.
 */
export const unregisterMeetingSchema = z
  .object({
    meetingId: meetingIdSchema,
  })
  .strict();

export type UnregisterMeetingInput = z.infer<
  typeof unregisterMeetingSchema
>;

/**
 * 5. Update meeting status (admin only).
 *
 * The status enum is bound to `MEETING_STATUS` so the client cannot
 * invent arbitrary states. The repository performs the actual
 * transition validation against the current status.
 */
export const updateMeetingStatusSchema = z
  .object({
    id: meetingIdSchema,
    status: z.enum(MEETING_STATUS, {
      error: "Hali si sahihi.",
    }),
  })
  .strict();

export type UpdateMeetingStatusInput = z.infer<
  typeof updateMeetingStatusSchema
>;

/**
 * 6. List meetings (public + admin views share this shape).
 *
 * Optional status filter restricted to the allowed lifecycle
 * values; `search` matches the meeting title.
 */
export const listMeetingsSchema = z
  .object({
    status: z
      .enum(MEETING_STATUS, {
        error: "Hali si sahihi.",
      })
      .optional(),
    search: z
      .string()
      .trim()
      .max(100, "Utafutaji halipaswi kuwa na herufi zaidi ya 100.")
      .optional(),
  })
  .strict();

export type ListMeetingsInput = z.infer<
  typeof listMeetingsSchema
>;

/**
 * Re-export the status enum type for convenience so schema consumers
 * can import a single path.
 */
export type { MeetingStatus };